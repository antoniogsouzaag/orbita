// @vitest-environment jsdom
import * as React from "react";
import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { HermesIntegration } from "@/components/agents/hermes-integration";
import { sendHermes, checkHermes, executeMaintenance, executeWork } from "@/app/actions/hermes";
vi.mock("@/app/actions/hermes",()=>({sendHermes:vi.fn(),checkHermes:vi.fn(),executeMaintenance:vi.fn(),executeWork:vi.fn()}));
vi.mock("sonner",()=>({toast:Object.assign(vi.fn(),{error:vi.fn()})}));
vi.mock("@/components/ui/dialog",()=>({Dialog:({open,children}:{open:boolean;children:React.ReactNode})=>open?children:null,DialogContent:({children,title,description}:{children:React.ReactNode;title:string;description:string})=>React.createElement("section",null,title,description,children)}));
let host: HTMLDivElement;
let mounted: Root;
const config={enabled:true,endpointConfigured:true,secretConfigured:true};
beforeEach(()=>{Object.assign(globalThis,{IS_REACT_ACT_ENVIRONMENT:true});host=document.createElement("div");document.body.append(host);mounted=createRoot(host);vi.clearAllMocks();sessionStorage.clear();});
afterEach(async()=>{await act(async()=>mounted.unmount());host.remove();vi.useRealTimers();});
it("trabalho genérico é primário, não duplica e conserva pedido incerto",async()=>{
 vi.mocked(executeWork).mockRejectedValue(new Error("network"));
 await act(async()=>mounted.render(React.createElement(HermesIntegration,{config,initial:[]})));
 expect(host.querySelector("button")?.textContent).toBe("Encaminhar trabalho");
 await act(async()=>host.querySelector("button")!.click());
 for (const [label,value] of [["Título do trabalho","Investigar VPS03"],["Brief do trabalho","Investigue o problema"],["Critério de aceite","Teste real"]]) {
  const field=host.querySelector(`[aria-label="${label}"]`)!;
  await act(async()=>{Object.getOwnPropertyDescriptor(field.tagName === "INPUT" ? HTMLInputElement.prototype : HTMLTextAreaElement.prototype,"value")!.set!.call(field,value);field.dispatchEvent(new Event("input",{bubbles:true}));});
 }
 const form=host.querySelector('form[aria-label="Encaminhar trabalho"]')!;
 await act(async()=>{form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));});
 expect(executeWork).toHaveBeenCalledTimes(1);
 await act(async()=>form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true})));
 expect(executeWork).toHaveBeenCalledTimes(2);
 expect(vi.mocked(executeWork).mock.calls[0]).toEqual(vi.mocked(executeWork).mock.calls[1]);
 expect(executeWork).toHaveBeenCalledWith({title:"Investigar VPS03",brief:"Investigue o problema",acceptance:"Teste real"});
 expect(host.textContent).toContain("não aprova negócio, despesa ou destruição");
 const reset=[...host.querySelectorAll("button")].find(b=>b.textContent==="Iniciar outro trabalho explicitamente");expect(reset).toBeDefined();
 await act(async()=>reset!.click());
 expect((host.querySelector('input[aria-label="Título do trabalho"]') as HTMLInputElement).value).toBe("");
 expect(host.querySelector("fieldset")!.disabled).toBe(false);
});
it("oferece manutenção separada, exige tarefa explícita e conserva UUID em retry incerto",async()=>{
 vi.mocked(executeMaintenance).mockRejectedValue(new Error("network"));
 await act(async()=>mounted.render(React.createElement(HermesIntegration,{config,initial:[]})));
 await act(async()=>[...host.querySelectorAll("button")].find(b=>b.textContent==="Executar manutenção")!.click());
 expect(host.textContent).toContain("Recuperar Maia");
 expect(host.textContent).toContain("Monitorar domínio");
 const form=host.querySelector('form[aria-label="Manutenção operacional"]')!;
 expect(form).not.toBeNull();
 const task=host.querySelector('input[aria-label="UUID da tarefa empresarial"]')!;
 await act(async()=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value")!.set!.call(task,"12345678-1234-4234-8234-123456789abc");task.dispatchEvent(new Event("input",{bubbles:true}));});
 await act(async()=>{form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));});
 expect(executeMaintenance).toHaveBeenCalledTimes(1);
 await act(async()=>form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true})));
 expect(executeMaintenance).toHaveBeenCalledTimes(2);
 expect(vi.mocked(executeMaintenance).mock.calls[0][0]).toEqual(vi.mocked(executeMaintenance).mock.calls[1][0]);
 expect(vi.mocked(executeMaintenance).mock.calls[0][0]).toMatchObject({operation:"maia.recover",task:{id:"12345678-1234-4234-8234-123456789abc"}});
 expect(sendHermes).not.toHaveBeenCalled();
});
it("só cria tarefa por opção explícita e envia domínio com notas no servidor",async()=>{
 vi.mocked(executeMaintenance).mockResolvedValue({id:"domain",action:"maintenance.execute",status:"accepted",createdAt:new Date().toISOString(),checkedAt:new Date().toISOString(),detail:"Recebido"});
 await act(async()=>mounted.render(React.createElement(HermesIntegration,{config,initial:[]})));
 await act(async()=>[...host.querySelectorAll("button")].find(b=>b.textContent==="Executar manutenção")!.click());
 expect(host.querySelector('input[type="checkbox"]')!.hasAttribute("checked")).toBe(false);
 await act(async()=>{const select=host.querySelector("select")!;select.value="monitor.domain.ensure";select.dispatchEvent(new Event("change",{bubbles:true}));(host.querySelector('input[type="checkbox"]') as HTMLInputElement).click();});
 const domain=host.querySelector('input[aria-label="Domínio registrado"]')!;
 const notes=host.querySelector('textarea[aria-label="Contexto da tarefa"]')!;
 await act(async()=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value")!.set!.call(domain,"example.com.br");domain.dispatchEvent(new Event("input",{bubbles:true}));Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,"value")!.set!.call(notes,"Adicionar monitoramento autorizado");notes.dispatchEvent(new Event("input",{bubbles:true}));});
 await act(async()=>host.querySelector('form[aria-label="Manutenção operacional"]')!.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true})));
 expect(executeMaintenance).toHaveBeenCalledWith(expect.objectContaining({operation:"monitor.domain.ensure",domain:"example.com.br",task:{create:true,notes:"Adicionar monitoramento autorizado"}}));
});
it("não duplica análise quando o formulário é submetido duas vezes antes do React atualizar",async()=>{
 let resolve!: (value: Awaited<ReturnType<typeof sendHermes>>) => void;
 vi.mocked(sendHermes).mockImplementation(()=>new Promise(done=>{resolve=done;}));
 await act(async()=>mounted.render(React.createElement(HermesIntegration,{config,initial:[]})));
 await act(async()=>[...host.querySelectorAll("button")].find(b=>b.textContent==="Acionar Hermes")!.click());
 const text=host.querySelector("textarea")!;
 await act(async()=>{Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,"value")!.set!.call(text,"Analisar");text.dispatchEvent(new Event("input",{bubbles:true}));});
 await act(async()=>{const form=host.querySelector("form")!;form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));form.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));});
 expect(sendHermes).toHaveBeenCalledTimes(1);
 await act(async()=>resolve({id:"pending",action:"agent.analyze",status:"accepted",createdAt:new Date().toISOString(),checkedAt:new Date().toISOString(),detail:"Recebido"}));
});
it("aciona análise manual sem prazo nem lembrete e mostra pedido e retorno como texto",async()=>{
 vi.mocked(sendHermes).mockResolvedValue({id:"request",action:"agent.analyze",status:"completed",createdAt:new Date().toISOString(),checkedAt:new Date().toISOString(),detail:"Concluído",text:"Analisar operação",responseText:"<script>retorno</script>",agentExecution:true});
 await act(async()=>mounted.render(React.createElement(HermesIntegration,{config,initial:[]})));
 const trigger=[...host.querySelectorAll("button")].find(b=>b.textContent==="Acionar Hermes");expect(trigger).toBeDefined();
 await act(async()=>trigger!.click());
 expect(host.textContent).toContain("sem mudanças em produção ou clientes");
 expect(host.querySelector('input[type="datetime-local"]')).toBeNull();
 const text=host.querySelector("textarea")!;expect(text.maxLength).toBe(4000);
 await act(async()=>{Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,"value")!.set!.call(text,"Analisar operação");text.dispatchEvent(new Event("input",{bubbles:true}));});
 await act(async()=>host.querySelector("form")!.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true})));
 expect(sendHermes).toHaveBeenCalledExactlyOnceWith({action:"agent.analyze",params:{text:"Analisar operação"}});
 expect(host.textContent).toContain("Analisar operação");expect(host.textContent).toContain("<script>retorno</script>");expect(host.querySelector("script")).toBeNull();expect(checkHermes).not.toHaveBeenCalled();
});
